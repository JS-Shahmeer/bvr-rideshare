"""Builds src/components/map/basemap.ts: an offline vector basemap of the
Newcastle / Hunter / Port Stephens service region, so the in-app map renders
without any tile server or API key.

Source: Natural Earth 1:10m (public domain), clipped to the region.
  pip install shapely
  python3 scripts/build-basemap.py <dir with ne_10m_*.geojson>
Files from https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
"""

import json
import sys
from pathlib import Path

from shapely.geometry import box, mapping, shape

SRC = Path(sys.argv[1])
BBOX = box(151.2, -33.25, 152.5, -32.3)
LAYERS = {
    'land': 'ne_10m_land',
    'urban': 'ne_10m_urban_areas',
    'rivers': 'ne_10m_rivers_australia',
    'rail': 'ne_10m_railroads',
    'roads': 'ne_10m_roads',
}


def coords(geom):
    """GeoJSON geometry → nested [lat, lng] arrays as Leaflet expects, 4 dp."""
    def flip(ring):
        return [[round(y, 4), round(x, 4)] for x, y in ring]

    g = mapping(geom)
    t = g['type']
    if t == 'Polygon':
        return [[flip(r) for r in g['coordinates']]]
    if t == 'MultiPolygon':
        return [[flip(r) for r in p] for p in g['coordinates']]
    if t == 'LineString':
        return [flip(g['coordinates'])]
    if t == 'MultiLineString':
        return [flip(l) for l in g['coordinates']]
    return []


out = {}
for key, name in LAYERS.items():
    shapes = []
    for f in json.loads((SRC / f'{name}.geojson').read_text())['features']:
        g = shape(f['geometry'])
        if not g.intersects(BBOX):
            continue
        clipped = g.intersection(BBOX).simplify(0.0003)
        if not clipped.is_empty:
            shapes.extend(coords(clipped))
    out[key] = shapes

ts = Path(__file__).resolve().parent.parent / 'src/components/map/basemap.ts'
ts.write_text(
    '/* eslint-disable */\n'
    '// Generated by scripts/build-basemap.py from Natural Earth 1:10m (public domain). Do not edit.\n'
    'export const BASEMAP: Record<string, unknown> = '
    + json.dumps(out, separators=(',', ':'))
    + ';\n'
)
print({k: len(v) for k, v in out.items()}, ts.stat().st_size, 'bytes')
