// Inlines Leaflet into src/components/map/leaflet.ts so the in-app map works
// without a CDN. Re-run after upgrading the leaflet dev dependency:
//   node scripts/vendor-leaflet.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const dist = (f) => readFileSync(require.resolve(`leaflet/dist/${f}`), 'utf8');
const { version } = require('leaflet/package.json');

writeFileSync(
  new URL('../src/components/map/leaflet.ts', import.meta.url),
  `/* eslint-disable */\n// Generated by scripts/vendor-leaflet.mjs from leaflet@${version} (BSD-2-Clause). Do not edit.\n` +
    `export const LEAFLET_CSS = ${JSON.stringify(dist('leaflet.css'))};\n` +
    `export const LEAFLET_JS = ${JSON.stringify(dist('leaflet.js'))};\n`,
);
